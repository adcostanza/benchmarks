#!/usr/bin/env python3
"""Paired stock-vs-Swift analysis on the vision suite, and the slim per-row files.

Usage: analysis.py <suite-dir>   (the rebuilt suite: DI_SUITE, contains vision-rows.jsonl)
Reads results/{stock-nvfp4,swift-nvfp4}/run/{results.jsonl,vision-scores.json}.
Writes uncertainty.md and results/<label>/rows-slim.jsonl (run id, benchmark, status, latency; choice and
correct for rows with more than two options, see README "Per-row files").
Resampling is over rows within each benchmark with the kit's chance values held fixed; rows are treated as
independent (CharXiv figures, Winoground pairs and BLINK items are not), so the intervals are optimistic.
"""
import json, random, sys, os
here = os.path.dirname(os.path.abspath(__file__))
suite = sys.argv[1]
labels = ["stock-nvfp4", "swift-nvfp4"]
gold = {}; nopt = {}
for l in open(os.path.join(suite, "vision-rows.jsonl")):
    r = json.loads(l); gold[r["id"]] = (r["benchmark"], r["expected"]["answer"]); nopt[r["id"]] = len(r["questions"]["answer"]["criteria"])
res = {}
for lab in labels:
    d = {}
    for l in open(f"{here}/results/{lab}/run/results.jsonl"):
        r = json.loads(l)
        a = r["response"]["answers"]["answer"] if r["status"] == "ok" else None
        d[r["run_id"]] = (r["status"], a["choice"] if a else None, r["total_wall_ms"])
    res[lab] = d
scores = {lab: json.load(open(f"{here}/results/{lab}/run/vision-scores.json")) for lab in labels}
bm = scores[labels[0]]["benchmarks"]
W = {b: v["weight"] for b, v in bm.items()}
chance = {b: v["chance"] for b, v in bm.items()}
ids = {b: [i for i, (bb, _) in gold.items() if bb == b] for b in bm}
corr = {lab: {i: int(res[lab][i][1] == gold[i][1]) for i in gold} for lab in labels}

def skills(vec, idx):  # vec: id -> 0/1 ; idx: list of ids per benchmark
    return {b: max(0.0, min(1.0, (sum(vec[i] for i in idx[b]) / len(idx[b]) - chance[b]) / (1 - chance[b]))) for b in idx}
def index(s): return 100 * sum(W[b] * s[b] for b in s) / sum(W.values())

for lab in labels:  # reproduce the kit's number
    ix = index(skills(corr[lab], ids))
    assert abs(ix - scores[lab]["public_vision_index"]) < 1e-6, (lab, ix)

random.seed(0)
N = 2000
draws = {lab: [] for lab in labels}; diff = []; bdiff = {b: [] for b in bm}
for _ in range(N):
    idx = {b: random.choices(ids[b], k=len(ids[b])) for b in ids}
    s = {lab: skills(corr[lab], idx) for lab in labels}
    for lab in labels: draws[lab].append(index(s[lab]))
    diff.append(index(s[labels[0]]) - index(s[labels[1]]))
    for b in bm: bdiff[b].append(100 * (s[labels[0]][b] - s[labels[1]][b]))
def ci(x): x = sorted(x); return x[int(0.025 * len(x))], x[int(0.975 * len(x)) - 1]
out = ["# Stock vs Swift, paired row bootstrap", "",
       f"Generated by `analysis.py` ({N} resamples of rows within each benchmark, seed 0; chance held fixed; rows treated as independent, so the intervals are optimistic). Reproduces the kit's public index for both configs to 1e-6 before resampling.", "",
       "| | public index | 95% interval |", "|---|---:|---|"]
for lab in labels:
    lo, hi = ci(draws[lab]); out.append(f"| {lab} | {scores[lab]['public_vision_index']:.2f} | {lo:.2f} to {hi:.2f} |")
lo, hi = ci(diff)
out.append(f"| stock − Swift | {scores[labels[0]]['public_vision_index'] - scores[labels[1]]['public_vision_index']:+.2f} | {lo:+.2f} to {hi:+.2f} |")
out += ["", "Per benchmark, skill points (stock − Swift) and rows where exactly one config is right:", "",
        "| Benchmark | rows | stock − Swift | 95% interval | only stock right | only Swift right |", "|---|---:|---:|---|---:|---:|"]
for b in bm:
    s0 = 100 * skills(corr[labels[0]], ids)[b]; s1 = 100 * skills(corr[labels[1]], ids)[b]
    lo, hi = ci(bdiff[b])
    o0 = sum(1 for i in ids[b] if corr[labels[0]][i] and not corr[labels[1]][i]); o1 = sum(1 for i in ids[b] if corr[labels[1]][i] and not corr[labels[0]][i])
    out.append(f"| {b} | {len(ids[b])} | {s0 - s1:+.2f} | {lo:+.2f} to {hi:+.2f} | {o0} | {o1} |")
agree = sum(1 for i in gold if res[labels[0]][i][1] == res[labels[1]][i][1])
out += ["", f"Same letter from both configs on {agree} of {len(gold)} rows ({100 * agree / len(gold):.1f}%)."]
open(f"{here}/uncertainty.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))

for lab in labels:
    with open(f"{here}/results/{lab}/rows-slim.jsonl", "w") as f:
        for l in open(f"{here}/results/{lab}/run/results.jsonl"):
            r = json.loads(l); i = r["run_id"]; b = r["benchmark"]
            row = {"run_id": i, "benchmark": b, "status": r["status"], "total_wall_ms": round(r["total_wall_ms"], 1)}
            if nopt[i] > 2:  # with two options, choice + correct would reveal the answer key
                row["choice"] = res[lab][i][1]; row["correct"] = corr[lab][i]
            f.write(json.dumps(row, separators=(",", ":")) + "\n")
