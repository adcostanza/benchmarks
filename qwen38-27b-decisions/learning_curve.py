#!/usr/bin/env python3
"""How many labeled cases does "T per type" need? Host side, CPU only, from the stored answers.

For each NVFP4 config and each dataset with a fit split separate from its scored split (every
transfer.py target except PubMedQA, which has no fit split, and Typed Decision Bench, whose only
split is the scored one), fits T per type (calibrate.fit, as transfer.py) on n cases drawn at
random from the fit split, then scores the test split. A case can hold several questions, so n counts cases, not questions. Each n is drawn SEEDS times; cells show the median metric
over draws with the [10th, 90th] percentile, and "share" is the median fraction of the full-split
fit's gain over raw ((m_n - raw) / (m_full - raw); 1 = as good as fitting on the whole split,
below 0 = worse than raw).

Usage (host, from this folder):
  uv run --no-project --with pyarrow --with numpy --with scipy learning_curve.py "$DATASETS_DIR" \\
      > results-real/learning_curve.md
  ... learning_curve.py "$DATASETS_DIR" --td-train results-repeat/train --td-test results-repeat/test \\
      --real results-repeat/test --pass pass1 > results-repeat/learning_curve.md
"""
import argparse

import numpy as np

from transfer import CONFIGS, METRIC, SOURCES, TARGETS, calibrate, here, sets

NS = [25, 50, 100, 200, 500]
SEEDS = 20


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("datasets_dir")
    ap.add_argument("--td-train", default="results-train")
    ap.add_argument("--td-test", default="results")
    ap.add_argument("--real", default="results-real")
    ap.add_argument("--pass", dest="pas", default="pass1")
    args = ap.parse_args()
    roots = {"td_train": here / args.td_train, "td_test": here / args.td_test, "real": here / args.real}

    def path(c, key, sub):
        return roots[key] / c / sub / f"{args.pas}.jsonl"

    print("# Learning curve: T per type fitted on n cases of the fit split\n")
    print(f"Answers: `{args.td_train}`, `{args.td_test}`, `{args.real}`, {args.pas}. "
          f"{SEEDS} random draws per n; cells: median metric [p10, p90] over draws; share: median "
          "fraction of the full-split fit's gain over raw. Sets without answers in these roots are "
          "left out. Generated by `learning_curve.py`.\n")
    for c in CONFIGS:
        print(f"## `{c}`\n")
        for tname, (set_name, sub, key, split, home, metric, _) in TARGETS.items():
            if home is None or SOURCES[home][3] == split:
                continue
            s_set, s_sub, s_key, s_split = SOURCES[home]
            if not (path(c, key, sub).exists() and path(c, s_key, s_sub).exists()):
                continue
            ds = sets.get(set_name)
            tc, trows = ds.load(args.datasets_dir, split), calibrate.read_rows(path(c, key, sub))
            items = calibrate.decisions(ds, calibrate.read_rows(path(c, s_key, s_sub)),
                                        ds.load(args.datasets_dir, s_split))
            by_case = {}
            for it in items:
                by_case.setdefault(it["id"], []).append(it)
            ids = sorted(by_case)

            def score(fit_items):
                t = calibrate.fit(fit_items, False)[0]
                return ds.metrics(calibrate.calibrated_rows(ds, trows, tc, lambda cid: (t, {})), tc)[metric]

            raw, full = ds.metrics(trows, tc)[metric], score(items)
            print(f"### {tname} ({METRIC[metric]}; fit split {s_split}, {len(ids)} cases)\n")
            print(f"raw {raw:.4g}, full split {full:.4g}\n")
            print("| n | metric | share of full gain (median, worst draw) |\n|---|---|---|")
            rng = np.random.default_rng(0)
            for n in [n for n in NS if n < len(ids)]:
                ms = [score([i for cid in rng.choice(ids, n, replace=False) for i in by_case[cid]])
                      for _ in range(SEEDS)]
                shares = [(m - raw) / (full - raw) for m in ms]
                p10, p50, p90 = np.percentile(ms, [10, 50, 90])
                print(f"| {n} | {p50:.4g} [{p10:.4g}, {p90:.4g}] | {np.median(shares):.2f}, "
                      f"{min(shares):.2f} |")
            print()


if __name__ == "__main__":
    main()
