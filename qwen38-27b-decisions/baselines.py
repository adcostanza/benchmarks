"""CPU only: does the model carry signal on the image sets? Per set and config (pass 1, `test`):
KL from gold of the raw model (T = 1), of the model with its own validation-fitted T, of a uniform
guess, and of the validation split's mean gold distribution (a constant, fitted like a temperature);
plus top-answer accuracy against the gold mode, and (score sets) Spearman between the model's
expected rating and the gold mean rating. For Rapidata pairs it also prints how often the top answer is
`Image 2` (position check).

  uv run --no-project --with pyarrow --with numpy --with scipy --with pillow baselines.py /home/share/datasets > results-vision/baselines.md
"""
import sys
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr

here = Path(__file__).resolve().parent
sys.path.insert(0, str(here.parent / "scripts" / "decisions"))
import calibrate  # noqa: E402
import sets  # noqa: E402

SETS = [("CIFAR-10H", "cifar10h"), ("soft-digits", "soft-digits"), ("Rapidata pairs", "rapidata-style"),
        ("POPE", "pope"), ("VQAv2", "vqav2"), ("VizWiz", "vizwiz"),
        ("AVA", "ava"), ("KonIQ", "koniq10k"), ("Rapidata Likert", "rapidata-likert")]


def kl(g, lp):
    p = np.exp(lp - lp.max())
    p /= p.sum()
    m = g > 0
    return float(np.sum(g[m] * np.log(g[m] / np.clip(p[m], 1e-12, None))))


def meankl(items, lps):
    return float(np.mean([kl(i["g"], lp) for i, lp in zip(items, lps)]))


def main():
    root = sys.argv[1]
    print("# Signal check on the image sets (pass 1, `test`)\n")
    print("KL from gold (↓), mean over decisions. `raw` T = 1; `own fit` T fitted on the set's `validation`; "
          "`uniform` equal probability on every option; `val mean` the `validation` split's mean gold "
          "distribution as a constant guess. `acc` top answer = gold mode (ties count as a hit if the "
          "answer is a mode); `chance` is 1/options. `rho`: Spearman between the model's expected rating "
          "(probability-weighted option index) and the gold mean rating, `test` cases. `mean rating`: the model's mean expected rating raw (T = 1), after its own `validation`-fitted T, and the gold mean rating, on the scale's 1..N levels (score sets). Generated by `baselines.py`.\n")
    pos = {}
    for c in ["stock-nvfp4", "swift-nvfp4"]:
        print(f"## `{c}`\n\n| Set | decisions | raw | own fit | uniform | val mean | acc | chance | rho | mean rating raw / own fit / gold |\n|---|---|---|---|---|---|---|---|---|---|")
        for label, name in SETS:
            ds = sets.get(name)
            out = {}
            for sp in ("validation", "test"):
                rows = calibrate.read_rows(here / "results-vision" / c / f"{name}-{sp}" / "pass1.jsonl")
                out[sp] = calibrate.decisions(ds, rows, ds.load(root, sp))
            val, test = out["validation"], out["test"]
            T = calibrate.fit(val, False)[0]
            raw = meankl(test, [i["lp"] for i in test])
            own = meankl(test, [i["lp"] / T[i["type"]] for i in test])
            uni = meankl(test, [np.zeros(len(i["g"])) for i in test])
            # val mean: per type and option count
            prior = {}
            for i in val:
                prior.setdefault((i["type"], len(i["g"])), []).append(i["g"])
            prior = {k: np.mean(v, axis=0) for k, v in prior.items()}
            pm = meankl(test, [np.log(np.clip(prior[i["type"], len(i["g"])], 1e-12, None)) for i in test])
            acc = float(np.mean([i["g"][int(np.argmax(i["lp"]))] == i["g"].max() for i in test]))
            chance = float(np.mean([1 / len(i["g"]) for i in test]))
            rho, mr = "-", "-"
            if test[0]["type"] == "score":
                idx = np.arange(len(test[0]["g"]))
                pe = [float(np.sum(idx * np.exp(i["lp"]) / np.exp(i["lp"]).sum())) for i in test]
                ge = [float(np.sum(idx * i["g"])) for i in test]
                rho = f"{spearmanr(pe, ge)[0]:.3f}"
                pf = [float(np.sum(idx * np.exp(i["lp"] / T[i["type"]]) / np.exp(i["lp"] / T[i["type"]]).sum())) for i in test]
                mr = f"{np.mean(pe) + 1:.2f} / {np.mean(pf) + 1:.2f} / {np.mean(ge) + 1:.2f}"
            if name == "rapidata-style":
                pos[c] = (float(np.mean([int(np.argmax(i["lp"])) == 1 for i in test])),
                          float(np.mean([np.exp(i["lp"])[1] / np.exp(i["lp"]).sum() for i in test])),
                          float(np.mean([i["g"][1] for i in test])),
                          float(np.mean([(i["g"] == i["g"].max()).mean() for i in test])),
                          float(np.mean([i["g"][0] == i["g"].max() for i in test])),
                          float(np.mean([i["g"][1] == i["g"].max() for i in test])),
                          float(np.mean([(i["g"][0] == i["g"][1]) for i in test])))
            print(f"| {label} | {len(test)} | {raw:.3f} | {own:.3f} | {uni:.3f} | {pm:.3f} | {acc:.3f} | {chance:.3f} | {rho} | {mr} |")
        print()
    print("## Rapidata pairs: position of the answer (`test`, pass 1)\n\nThe image order is randomised per pair, "
          "so a model without a side preference answers `Image 2` on about the share of pairs whose gold favours it.\n\n"
          "| Config | top answer is `Image 2` | mean P(`Image 2`) | mean gold share of `Image 2` | tied gold pairs | accuracy of a random side | always `Image 1` | always `Image 2` |\n|---|---|---|---|---|---|---|---|")
    for c, (top, mp, gm, rand, a1, a2, ties) in pos.items():
        print(f"| {c} | {top:.3f} | {mp:.3f} | {gm:.3f} | {ties:.3f} | {rand:.3f} | {a1:.3f} | {a2:.3f} |")
    print("\n`accuracy` elsewhere in this file counts a tied gold pair as a hit for either answer, so a random side scores above 0.500.")


if __name__ == "__main__":
    main()
